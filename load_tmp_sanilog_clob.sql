  procedure load_one_file(p_filename in varchar2) is
  begin
    insert into tmp_sanilog (tekst, clobje)
    values (p_filename, empty_clob())
    returning clobje into v_clob;

    v_bfile := bfilename('TMP_SANILOG_DIR', p_filename);

    dbms_lob.fileopen(v_bfile, dbms_lob.file_readonly);
    v_dest_offset := 1;
    v_src_offset := 1;

    dbms_lob.loadclobfromfile(
      dest_lob     => v_clob,
      src_bfile    => v_bfile,
      amount       => dbms_lob.lobmaxsize,
      dest_offset  => v_dest_offset,
      src_offset   => v_src_offset,
      bfile_csid   => nls_charset_id('AL32UTF8'),
      lang_context => v_lang_ctx,
      warning      => v_warning
    );

    dbms_lob.fileclose(v_bfile);
    v_inserted := v_inserted + 1;
  exception
    when others then
      if dbms_lob.isopen(v_bfile) = 1 then
        dbms_lob.fileclose(v_bfile);
      end if;
      raise;
  end load_one_file;
